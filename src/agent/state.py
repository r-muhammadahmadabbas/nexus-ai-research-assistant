"""
State schema for the LangGraph multi-agent system.
Maintains conversation history, agent outputs, and memory management fields.
"""
from typing import TypedDict, Annotated, Sequence
from langchain_core.messages import BaseMessage
import operator


class AgentState(TypedDict):
    """
    Shared state passed between all agents in the LangGraph workflow.

    Fields:
        messages:               Full conversation history (appended via reducer).
        conversation_summary:   Rolling summary of older messages (sliding window).
        clarity_status:         Output of Clarity Agent ('clear' | 'needs_clarification').
        clarification_question: Dynamic clarification question generated by Clarity Agent.
        confidence_score:       Research Agent's self-assessed confidence (0–10).
        validation_result:      Validator Agent output ('sufficient' | 'insufficient').
        research_data:          Raw research findings gathered by Research Agent.
        search_query:           The enriched search query built from conversation context.
        attempts:               Number of research loop iterations.
        active_agent:           Name of the currently executing agent (for frontend tracking).
    """
    messages: Annotated[Sequence[BaseMessage], operator.add]
    conversation_summary: str
    clarity_status: str
    clarification_question: str
    confidence_score: float
    validation_result: str
    research_data: str
    search_query: str
    attempts: int
    active_agent: str
